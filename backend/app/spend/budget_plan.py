"""Kế hoạch ngân sách năm sau (docs/design/spend-budget-plan.md).

A plan for fiscal year Y is built from what the module already knows, then adjusted by people:

* renewal   — an Opex (planned / active, fiscal year < Y, not yet renewed) whose next term(s)
              start inside Y. Amount = today's amount × number of terms × (1 + uplift %).
* committed — an Opex already booked in Y (planned / active: a renewal done early, an Opex
              generated by a Capex project, an item typed for next year). Amount as booked.
* capex     — a Capex project of fiscal year Y (draft projects are included but flagged).
* replace   — Data Center devices (Tài sản → Thiết bị Data Center) in use ≥ 5 years by the end of Y,
              one Capex line per business function (dc_assets.plan_suggestions). No price is known: the
              amount is typed in the plan; the line becomes a draft Capex once approved.
* extend    — the same devices kept in use instead (decision "Dùng tiếp": over budget, still good …) that
              have no HW warranty Opex to renew: one Opex line per business function; once approved it
              becomes a planned Opex listing their serials.
* new       — a line typed in the plan (new service, new project), applied to the real
              Opex / Capex tables once the plan is approved.

`suggest` is pure over the database (reads only). `refresh` merges the suggestions into a draft
plan without losing what people changed. `summary` and `actuals` compute every number shown on
screen and in Excel, so the two can never disagree.
"""
