STATUS_LABELS = {"draft": "Nháp", "submitted": "Chờ duyệt", "approved": "Đã duyệt", "superseded": "Đã thay thế"}
SOURCE_LABELS = {"renewal": "Gia hạn", "committed": "Đã ghi nhận", "capex": "Dự án Capex", "replace": "Thay thế thiết bị",
                 "extend": "Dùng tiếp thiết bị", "new": "Mới đề xuất"}
APPLIED_SOURCES = ("new", "replace", "extend")            # lines that become a real Opex / Capex once the plan is approved
PRIORITY_LABELS = {"must": "Bắt buộc", "should": "Nên có", "could": "Tuỳ chọn"}
PRIORITY_RANK = {"must": 0, "should": 1, "could": 2}
CAPEX_SPENT = ("approved", "in_progress", "closed")
OPEX_SPENT = ("planned", "active", "renewed")
MAX_LINES = 2000


# ---------------------------------------------------------------- arithmetic (pure)
def uplifted(base_net: int, pct: Decimal) -> int:
    return int((Decimal(base_net) * (Decimal(100) + Decimal(pct)) / Decimal(100)).quantize(Decimal(1), ROUND_HALF_UP))


def add_months(d: dt.date, months: int) -> dt.date:
    """Same day `months` later, clamped to the end of a shorter month (31/01 + 1 -> 28/02)."""
    m = d.month - 1 + months
    y, m = d.year + m // 12, m % 12 + 1
    return dt.date(y, m, min(d.day, calendar.monthrange(y, m)[1]))


def _term_months(start: dt.date, end: dt.date) -> int:
    """Length of a term in whole months (1..60), or 0 when it is not a whole number of months."""
    for k in range(1, 61):
        if k % 12 == 0 and fiscal.term_end(start, k // 12) == end:
            return k
        if add_months(start, k) - dt.timedelta(days=1) == end:
            return k
    return 0


def _next_term(start: dt.date, end: dt.date, prev_end: dt.date) -> Tuple[dt.date, dt.date]:
    """The term following one that ended on `prev_end`, as long as the original term
    (`start`..`end`). Month / year terms stay on the calendar (quarters on 01/01, 01/04 …;
    29/02 handled by fiscal.term_end); other terms keep their length in days."""
    nstart = prev_end + dt.timedelta(days=1)
    k = _term_months(start, end)
    if k and k % 12 == 0:
        return nstart, fiscal.term_end(nstart, k // 12)
    if k:
        return nstart, add_months(nstart, k) - dt.timedelta(days=1)
    return nstart, nstart + (end - start)


def renewal_starts(start: dt.date, end: dt.date, year_start: dt.date, year_end: dt.date) -> List[dt.date]:
    """Start dates of the renewals of a term (`start`..`end`) that fall inside [year_start, year_end]."""
    out: List[dt.date] = []
    cur_end = end
    for _ in range(400):                      # a daily term renewed for a year is the worst case
        s, e = _next_term(start, end, cur_end)
        if s > year_end:
            break
        if s >= year_start:
            out.append(s)
        cur_end = e
    return out


def line_amounts(line: BudgetPlanLine, plan: BudgetPlan) -> None:
    """Recompute the planned amount of an 'auto' line; gross always follows net and VAT."""
    if line.amount_mode == "auto":
        pct = Decimal(0)
        if line.source == "renewal":
            pct = Decimal(line.uplift_pct if line.uplift_pct is not None else plan.uplift_pct)
        elif line.uplift_pct is not None:
            pct = Decimal(line.uplift_pct)
        line.amount_net = uplifted(line.base_net, pct)
    line.amount_gross = service.gross_of(line.amount_net, Decimal(line.vat_pct))


# ---------------------------------------------------------------- suggestions
def suggest(db: Session, year: int, cfg: SpendSettings) -> List[Dict[str, Any]]:
    """Every line the module can propose for fiscal year `year`, from the current data."""
    ys, ye = fiscal.fiscal_range(year, cfg.fiscal_start_month)
    out: List[Dict[str, Any]] = []
    opex = (db.query(OpexItem).filter(OpexItem.status.in_(("planned", "active")), OpexItem.fiscal_year <= year)
            .order_by(OpexItem.end_date, OpexItem.code).all())
    for o in opex:
        common = {"kind": "opex", "sourceId": o.id, "sourceCode": o.code, "categoryId": o.category_id, "vendorId": o.vendor_id,
                  "costCenterId": o.cost_center_id, "title": o.title, "vatPct": Decimal(o.vat_pct)}
        if o.fiscal_year == year:
            out.append({**common, "source": "committed", "startDate": o.start_date, "terms": 1, "baseNet": o.amount_net,
                        "detail": service.ORIGIN_LABELS.get(o.origin, "")})
            continue
        if o.billing_cycle == "one_time":
            continue
        starts = renewal_starts(o.start_date, o.end_date, ys, ye)
        if starts:
            out.append({**common, "source": "renewal", "startDate": starts[0], "terms": len(starts),
                        "baseNet": o.amount_net * len(starts),
                        "detail": f"Hết hạn {service.date_vn(o.end_date)}" + (f" · {len(starts)} kỳ trong năm" if len(starts) > 1 else "")})
    projects = db.query(CapexProject).filter(CapexProject.fiscal_year == year, CapexProject.status != "closed").all()
    items = defaultdict(list)
    for it in db.query(CapexItem).filter(CapexItem.project_id.in_([p.id for p in projects] or [-1])).order_by(CapexItem.sort_order, CapexItem.id):
        items[it.project_id].append(it)
    for p in projects:
        its = items.get(p.id) or []
        if not its:
            continue
        net = sum(i.amount_net for i in its)
        gross = sum(i.amount_gross for i in its)
        # One line per project; category / VAT of its largest item (the totals keep the exact gross).
        big = max(its, key=lambda i: i.amount_net)
        vat = Decimal(100) * (Decimal(gross) - Decimal(net)) / Decimal(net) if net else Decimal(big.vat_pct)
        out.append({"kind": "capex", "source": "capex", "sourceId": p.id, "sourceCode": p.code, "categoryId": big.category_id,
                    "vendorId": big.vendor_id, "costCenterId": p.cost_center_id, "title": p.name,
                    "startDate": p.go_live_date, "terms": 1, "baseNet": net, "grossExact": gross,
                    "vatPct": vat.quantize(Decimal("0.01"), ROUND_HALF_UP),
                    "detail": "Nháp — chưa duyệt" if p.status == "draft" else ""})
    from .. import dc_assets
    out.extend(dc_assets.plan_suggestions(db, ys, ye))
    return out


def _apply_suggestion(line: BudgetPlanLine, s: Dict[str, Any], plan: BudgetPlan) -> None:
    line.kind, line.source, line.source_id, line.source_code = s["kind"], s["source"], s["sourceId"], s["sourceCode"]
    line.category_id, line.vendor_id, line.cost_center_id = s["categoryId"], s["vendorId"], s["costCenterId"]
    line.title = s["title"][:255]
    line.start_date, line.terms, line.base_net, line.vat_pct = s["startDate"], s["terms"], s["baseNet"], s["vatPct"]
    line.detail = (s.get("detail") or "")[:1000] or None
    line.stale = False
    line_amounts(line, plan)
    if line.amount_mode == "auto" and s.get("grossExact") is not None and line.uplift_pct in (None, 0):
        line.amount_gross = s["grossExact"]          # several VAT rates in one project: keep the exact sum


def refresh(db: Session, plan: BudgetPlan, cfg: SpendSettings, user: User) -> Dict[str, int]:
    """Merge the current suggestions into `plan` (draft only). Lines people touched keep their
    amount / decision; their reference data (base, dates, names) still follows the source."""
    sugg = {(s["source"], s["sourceId"]): s for s in suggest(db, plan.fiscal_year, cfg)}
    lines = db.query(BudgetPlanLine).filter(BudgetPlanLine.plan_id == plan.id).all()
    by_key = {(l.source, l.source_id): l for l in lines if l.source != "new"}
    stats = {"added": 0, "updated": 0, "removed": 0, "stale": 0}
    now = dt.datetime.utcnow()
    order = max([l.sort_order for l in lines] or [0])
    for key, s in sugg.items():
        line = by_key.get(key)
        if line is None:
            # The same Opex may move from "renewal" to "committed" once renewed early: drop the old key.
            other = by_key.get(("renewal" if key[0] == "committed" else "committed", key[1])) if key[0] in ("renewal", "committed") else None
            if other is not None and not _touched(other):
                db.delete(other)
                stats["removed"] += 1
            order += 1
            line = BudgetPlanLine(plan_id=plan.id, amount_mode="auto", priority=s.get("priority", "must"), included=True,
                                  sort_order=order)
            _apply_suggestion(line, s, plan)
            line.updated_at, line.updated_by = now, user.username
            db.add(line)
            stats["added"] += 1
        else:
            before = (line.base_net, line.start_date, line.terms, line.amount_net, line.amount_gross, line.title, line.stale, line.detail)
            _apply_suggestion(line, s, plan)
            if before != (line.base_net, line.start_date, line.terms, line.amount_net, line.amount_gross, line.title, line.stale, line.detail):
                line.updated_at, line.updated_by = now, user.username
                stats["updated"] += 1
    for key, line in by_key.items():
        if key in sugg or line.stale:
            continue
        if _touched(line):
            line.stale = True
            stats["stale"] += 1
        else:
            db.delete(line)
            stats["removed"] += 1
    return stats


def _touched(line: BudgetPlanLine) -> bool:
    return (line.amount_mode == "manual" or not line.included or line.priority != "must" or bool(line.note)
            or line.uplift_pct is not None)


# ---------------------------------------------------------------- summary
def _quarter(d: Optional[dt.date], cfg: SpendSettings, year: int) -> int:
    if d is None:
        return 1
    ys, ye = fiscal.fiscal_range(year, cfg.fiscal_start_month)
    d = min(max(d, ys), ye)
    return ((d.month - cfg.fiscal_start_month) % 12) // 3 + 1


def baseline(db: Session, year: int) -> Dict[str, Any]:
    """What fiscal year `year` costs today (same statuses as the budget report): Opex planned /
    active / renewed + Capex approved and later. Gross, by category id."""
    by_cat: Dict[int, int] = defaultdict(int)
    opex = capex = 0
    for o in db.query(OpexItem).filter(OpexItem.fiscal_year == year, OpexItem.status.in_(OPEX_SPENT)):
        opex += o.amount_gross
        by_cat[o.category_id] += o.amount_gross
    rows = (db.query(CapexItem).join(CapexProject, CapexProject.id == CapexItem.project_id)
            .filter(CapexProject.fiscal_year == year, CapexProject.status.in_(CAPEX_SPENT)).all())
    for i in rows:
        capex += i.amount_gross
        by_cat[i.category_id] += i.amount_gross
    return {"fiscalYear": year, "opex": opex, "capex": capex, "total": opex + capex, "byCategory": dict(by_cat)}


def summary(db: Session, plan: BudgetPlan, lines: List[BudgetPlanLine], cfg: SpendSettings) -> Dict[str, Any]:
    cats = {c.id: c for c in db.query(SpendCategory).all()}
    inc = [l for l in lines if l.included]
    total = sum(l.amount_gross for l in inc)
    by_kind = {"opex": sum(l.amount_gross for l in inc if l.kind == "opex"),
               "capex": sum(l.amount_gross for l in inc if l.kind == "capex")}
    by_source = {s: sum(l.amount_gross for l in inc if l.source == s) for s in SOURCE_LABELS}
    by_priority = {p: sum(l.amount_gross for l in inc if l.priority == p) for p in PRIORITY_LABELS}
    quarters = [0, 0, 0, 0]
    for l in inc:
        quarters[_quarter(l.start_date, cfg, plan.fiscal_year) - 1] += l.amount_gross
    base = baseline(db, plan.fiscal_year - 1)
    by_cat: Dict[int, Dict[str, Any]] = {}
    for cid, amt in base["byCategory"].items():
        by_cat.setdefault(cid, {"plan": 0, "baseline": 0})["baseline"] = amt
    for l in inc:
        by_cat.setdefault(l.category_id, {"plan": 0, "baseline": 0})["plan"] += l.amount_gross
    cat_rows = []
    for cid, v in by_cat.items():
        c = cats.get(cid)
        cat_rows.append({"categoryId": cid, "category": c.name if c else "—", "plan": v["plan"], "baseline": v["baseline"],
                         "delta": v["plan"] - v["baseline"], "deltaPct": _pct(v["baseline"], v["plan"])})
    cat_rows.sort(key=lambda r: -r["plan"])
    # Ceiling: lines ranked by priority (then their order); what does not fit is above the cut line.
    cut = []
    if plan.budget_cap is not None:
        run = 0
        for l in sorted(inc, key=lambda l: (PRIORITY_RANK[l.priority], l.sort_order, l.id or 0)):
            run += l.amount_gross
            if run > plan.budget_cap:
                cut.append(l.id)
    renew_base = sum(l.base_net for l in inc if l.source == "renewal")
    renew_plan = sum(l.amount_net for l in inc if l.source == "renewal")
    return {
        "total": total, "count": len(inc), "excludedCount": len(lines) - len(inc),
        "excludedTotal": sum(l.amount_gross for l in lines if not l.included),
        "byKind": by_kind, "bySource": by_source, "byPriority": by_priority, "byQuarter": quarters,
        "byCategory": cat_rows, "baseline": {k: base[k] for k in ("fiscalYear", "opex", "capex", "total")},
        "deltaPct": _pct(base["total"], total), "renewalUplift": renew_plan - renew_base,
        "cap": plan.budget_cap, "overCap": (total - plan.budget_cap) if plan.budget_cap is not None and total > plan.budget_cap else 0,
        "cutLineIds": cut, "staleCount": sum(1 for l in lines if l.stale),
    }


def _pct(old: int, new: int) -> Optional[float]:
    return round((new - old) * 100.0 / old, 1) if old else None


# ---------------------------------------------------------------- plan vs actual (approved plans)
def actuals(db: Session, plan: BudgetPlan, lines: List[BudgetPlanLine]) -> Dict[str, Any]:
    """What fiscal year Y really holds now, line by line, plus what was booked outside the plan."""
    y = plan.fiscal_year
    opex_y = {o.id: o for o in db.query(OpexItem).filter(OpexItem.fiscal_year == y, OpexItem.status.in_(OPEX_SPENT))}
    by_prev = defaultdict(list)
    for o in db.query(OpexItem).filter(OpexItem.renewed_from_id.isnot(None)):
        by_prev[o.renewed_from_id].append(o)
    capex_y = {p.id: p for p in db.query(CapexProject).filter(CapexProject.fiscal_year == y)}
    capex_gross = defaultdict(int)
    for i in db.query(CapexItem).filter(CapexItem.project_id.in_(list(capex_y) or [-1])):
        capex_gross[i.project_id] += i.amount_gross
    codes_opex = {o.code: o for o in opex_y.values()}
    codes_capex = {p.code: p for p in capex_y.values()}
    used_opex, used_capex = set(), set()
    per_line: Dict[int, Dict[str, Any]] = {}
    for l in lines:
        actual, refs = 0, []
        if l.source == "renewal" and l.source_id:
            # Follow the renewal chain from the planned Opex; count the terms that fell into Y.
            todo, seen = [l.source_id], set()
            while todo:
                oid = todo.pop()
                for n in by_prev.get(oid, []):
                    if n.id in seen:
                        continue
                    seen.add(n.id)
                    todo.append(n.id)
                    if n.id in opex_y:
                        actual += n.amount_gross
                        refs.append(n.code)
                        used_opex.add(n.id)
        elif l.source == "committed" and l.source_id in opex_y:
            o = opex_y[l.source_id]
            actual, refs = o.amount_gross, [o.code]
            used_opex.add(o.id)
        elif l.source == "capex" and l.source_id in capex_y:
            p = capex_y[l.source_id]
            used_capex.add(p.id)
            if p.status in CAPEX_SPENT:
                actual, refs = capex_gross[p.id], [p.code]
        elif l.source in APPLIED_SOURCES and l.applied_code:
            if l.applied_code in codes_opex:
                o = codes_opex[l.applied_code]
                actual, refs = o.amount_gross, [o.code]
                used_opex.add(o.id)
            elif l.applied_code in codes_capex:
                p = codes_capex[l.applied_code]
                used_capex.add(p.id)
                if p.status in CAPEX_SPENT:
                    actual, refs = capex_gross[p.id], [p.code]
        planned = l.amount_gross if l.included else 0
        per_line[l.id] = {"actual": actual, "refs": refs, "variance": actual - planned}
    unplanned = [{"kind": "opex", "code": o.code, "title": o.title, "amountGross": o.amount_gross}
                 for o in opex_y.values() if o.id not in used_opex]
    unplanned += [{"kind": "capex", "code": p.code, "title": p.name, "amountGross": capex_gross[p.id]}
                  for p in capex_y.values() if p.id not in used_capex and p.status in CAPEX_SPENT]
    unplanned.sort(key=lambda r: -r["amountGross"])
    planned_total = sum(l.amount_gross for l in lines if l.included)
    actual_total = sum(v["actual"] for v in per_line.values()) + sum(r["amountGross"] for r in unplanned)
    return {"lines": per_line, "unplanned": unplanned, "plannedTotal": planned_total, "actualTotal": actual_total,
            "unplannedTotal": sum(r["amountGross"] for r in unplanned), "variance": actual_total - planned_total,
            "usedPct": round(actual_total * 100.0 / planned_total, 1) if planned_total else None}


# ---------------------------------------------------------------- apply (approved plan -> real Opex / Capex)
def apply(db: Session, plan: BudgetPlan, cfg: SpendSettings, user: User, request: Optional[Request]) -> Dict[str, List[str]]:
    """Create the Opex (status Dự kiến) / Capex (Nháp) of every included `new` / `replace` line not applied yet.
    Renewals stay with the normal Gia hạn flow — the plan amount is the yardstick, not a booking."""
    if plan.status != "approved":
        raise HTTPException(409, "Chỉ áp dụng được kế hoạch đã duyệt.")
    out = {"created": [], "skipped": []}
    ys, _ye = fiscal.fiscal_range(plan.fiscal_year, cfg.fiscal_start_month)
    lines = (db.query(BudgetPlanLine).filter(BudgetPlanLine.plan_id == plan.id, BudgetPlanLine.source.in_(APPLIED_SOURCES),
                                             BudgetPlanLine.included.is_(True), BudgetPlanLine.applied_code.is_(None))
             .order_by(BudgetPlanLine.sort_order, BudgetPlanLine.id).all())
    for l in lines:
        start = l.start_date or ys
        if l.kind == "opex":
            if l.vendor_id is None:
                out["skipped"].append(f"{l.title}: thiếu nhà cung cấp")
                continue
            assets = []
            if l.source == "extend" and l.source_id:
                from .. import dc_assets
                assets = [{"serial": s, "description": "Thiết bị Data Center dùng tiếp"}
                          for s in dc_assets.extend_serials(db, l.source_id, ys, _ye)]
            o = service.create(db, {
                "categoryId": l.category_id, "title": l.title, "description": "\n".join(x for x in (l.note, l.detail) if x) or None,
                "vendorId": l.vendor_id, "assets": assets,
                "startDate": start.isoformat(), "endDate": fiscal.term_end(start, 1).isoformat(), "billingCycle": "yearly",
                "amountNet": l.amount_net, "vatPct": l.vat_pct, "amountGross": l.amount_gross, "fiscalYear": plan.fiscal_year, "costCenterId": l.cost_center_id,
                "ownerName": user.display_name or user.username, "status": "planned",
            }, cfg, user, request)
            _claim_line(db, l, o.code, user)
        else:
            p = CapexProject(code=codes.next_code(db, "capex", plan.fiscal_year), fiscal_year=plan.fiscal_year, name=l.title,
                             description="\n".join(x for x in (l.note, l.detail) if x) or None, cost_center_id=l.cost_center_id,
                             owner_name=user.display_name or user.username,
                             status="draft", go_live_date=l.start_date, created_by=user.username, row_version=1)
            db.add(p)
            db.flush()
            db.add(CapexItem(project_id=p.id, category_id=l.category_id, description=l.title[:255], vendor_id=l.vendor_id,
                             quantity=1, amount_net=l.amount_net, vat_pct=l.vat_pct, amount_gross=l.amount_gross,
                             start_date=l.start_date, coverage_years=0))
            service.audit(db, user, request, "spend.capex.create", code=p.code, plan=plan_label(plan))
            _claim_line(db, l, p.code, user)
        out["created"].append(l.applied_code)
    service.audit(db, user, request, "spend.plan.apply", plan=plan_label(plan), created=out["created"], skipped=out["skipped"])
    return out


def _claim_line(db: Session, line: BudgetPlanLine, code: str, user: User) -> None:
    """Mark the line applied only if nobody else did: UPDATE ... WHERE applied_code IS NULL.
    0 rows -> a concurrent apply got there first; raising rolls back the Opex / Capex this
    request just created, so each line yields exactly one booking."""
    now = dt.datetime.utcnow()
    res = db.execute(update(BudgetPlanLine)
                     .where(BudgetPlanLine.id == line.id, BudgetPlanLine.applied_code.is_(None))
                     .values(applied_code=code, updated_at=now, updated_by=user.username)
                     .execution_options(synchronize_session=False))
    if res.rowcount != 1:
        raise HTTPException(409, "Kế hoạch đang được áp dụng bởi thao tác khác — tải lại để xem kết quả.")
    for attr, val in (("applied_code", code), ("updated_at", now), ("updated_by", user.username)):
        set_committed_value(line, attr, val)


def plan_label(plan: BudgetPlan) -> str:
    return f"KH-{plan.fiscal_year}-v{plan.version}"
